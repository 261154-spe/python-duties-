# Truth Value Testing
# https://docs.python.org/3/library/stdtypes.html#truth-value-testing

# Empty text is False
print(bool(""))

# Text with zero is True
print(bool("0"))

# Number zero is False
print(bool(0))

# Decimal zero is False
print(bool(0.0))

# Text False is True
print(bool("False"))

